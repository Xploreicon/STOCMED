// Disposable localhost-only contract test. Never accepts a production URL.
const { Client } = require('pg');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const pharmacy='10000000-0000-4000-8000-000000000001';
const otherPharmacy='10000000-0000-4000-8000-000000000002';
const user='20000000-0000-4000-8000-000000000001';
const ids=[1,2,3,4,5].map(n=>`30000000-0000-4000-8000-00000000000${n}`);
const c=new Client({host:'127.0.0.1',port:Number(process.env.RECOVERY_TEST_PORT||55491),database:'postgres',user:process.env.USER,connectionTimeoutMillis:5000});
(async()=>{
  await c.connect();
  await c.query(`
    CREATE ROLE anon; CREATE ROLE authenticated;
    CREATE SCHEMA auth;
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    CREATE TABLE pharmacies(id uuid PRIMARY KEY,user_id uuid);
    CREATE TABLE pharmacy_inventory(id uuid PRIMARY KEY,pharmacy_id uuid REFERENCES pharmacies(id),product_id uuid,item_type text,barcode text,deleted_at timestamptz,is_listed boolean DEFAULT true,quantity_in_stock int DEFAULT 7,updated_at timestamptz DEFAULT now());
    CREATE TABLE reservations(inventory_id uuid,status text,expires_at timestamptz);
    CREATE FUNCTION verify_gated_sp_action(uuid,text,text,text) RETURNS boolean LANGUAGE sql AS $$ SELECT coalesce(current_setting('test.sp_allowed',true),'true')='true' $$;
  `);
  await c.query('insert into pharmacies values ($1,$2),($3,$4)',[pharmacy,user,otherPharmacy,'20000000-0000-4000-8000-000000000002']);
  for(let i=0;i<ids.length;i++) await c.query("insert into pharmacy_inventory(id,pharmacy_id,item_type,deleted_at,is_listed) values($1,$2,'store',case when $3 then now()-interval '90 days' else null end,not $3)",[ids[i],i===2?otherPharmacy:pharmacy,i===4]);
  await c.query(fs.readFileSync('supabase/migrations/20261025132235_inventory_recovery_bin.sql','utf8'));
  assert.ok((await c.query('select recovery_expires_at>now() as recoverable from pharmacy_inventory where id=$1',[ids[4]])).rows[0].recoverable,'legacy delisted rows get a full window');
  const call=async(action,selection=ids.slice(0,2))=>(await c.query('select bulk_change_pharmacy_inventory($1,$2,$3,$4,null) result',[pharmacy,selection,action,'Duplicate item'])).rows[0].result;
  assert.equal((await call('remove')).code,'NOT_FOUND','anonymous cannot remove stock');
  await c.query("select set_config('request.jwt.claim.sub',$1,false)",[user]);
  assert.equal((await call('remove',[ids[0],ids[2]])).code,'NOT_FOUND','cross-tenant ID rejects whole request');
  assert.equal((await c.query('select count(*)::int n from pharmacy_inventory where deleted_at is null')).rows[0].n,4);
  await c.query("select set_config('test.sp_allowed','false',false)");
  assert.equal((await call('remove')).code,'SP_AUTH_REQUIRED');
  assert.equal((await c.query('select count(*)::int n from inventory_removal_events')).rows[0].n,0);
  await c.query("select set_config('test.sp_allowed','true',false)");
  await c.query("insert into reservations values($1,'active',now()+interval '1 hour')",[ids[0]]);
  assert.equal((await call('remove')).code,'ACTIVE_RESERVATION');
  await c.query('delete from reservations');
  assert.equal((await call('remove')).changed,2);
  let rows=(await c.query('select *,recovery_expires_at-deleted_at as recovery_window from pharmacy_inventory where id=any($1)',[ids.slice(0,2)])).rows;
  assert.ok(rows.every(r=>r.deleted_at&&!r.is_listed&&r.quantity_in_stock===7));
  assert.equal(rows[0].recovery_window.days,60);
  const deadline=rows[0].recovery_expires_at.toISOString();
  assert.equal((await call('remove')).changed,0,'retries do not extend recovery or duplicate events');
  assert.equal((await c.query('select recovery_expires_at from pharmacy_inventory where id=$1',[ids[0]])).rows[0].recovery_expires_at.toISOString(),deadline);
  assert.equal((await c.query('select count(*)::int n from inventory_removal_events')).rows[0].n,2);
  assert.equal((await call('restore')).changed,2);
  assert.ok((await c.query('select * from pharmacy_inventory where id=any($1)',[ids.slice(0,2)])).rows.every(r=>!r.deleted_at&&r.is_listed&&r.quantity_in_stock===7));
  await call('remove');
  await c.query("update pharmacy_inventory set recovery_expires_at=now() where id=$1",[ids[0]]);
  assert.equal((await call('restore')).code,'RECOVERY_EXPIRED');
  assert.ok((await c.query('select deleted_at from pharmacy_inventory where id=$1',[ids[1]])).rows[0].deleted_at,'mixed expired selection is atomic');
  const single=(await c.query('select restore_pharmacy_inventory_item($1,null) result',[ids[0]])).rows[0].result;
  assert.equal(single.code,'RECOVERY_EXPIRED','legacy single restore cannot bypass deadline');
  await c.query('update pharmacy_inventory set barcode=$1 where id=any($2)',['12345678',[ids[1],ids[3]]]);
  assert.equal((await call('restore',[ids[1]])).code,'ACTIVE_DUPLICATE');
  assert.equal((await c.query("select has_table_privilege('authenticated','inventory_removal_events','UPDATE') allowed")).rows[0].allowed,false);
  assert.equal((await c.query("select has_function_privilege('anon','bulk_change_pharmacy_inventory(uuid,uuid[],text,text,text)','EXECUTE') allowed")).rows[0].allowed,false);
  await c.query('GRANT USAGE ON SCHEMA auth TO authenticated; GRANT SELECT ON pharmacies TO authenticated; SET ROLE authenticated');
  assert.equal((await c.query('select count(*)::int n from inventory_removal_events')).rows[0].n,6,'owner sees their audit events');
  await c.query("select set_config('request.jwt.claim.sub',$1,false)",['20000000-0000-4000-8000-000000000002']);
  assert.equal((await c.query('select count(*)::int n from inventory_removal_events')).rows[0].n,0,'another tenant cannot see removal events');
  console.log('PASS: bulk removal/restore, 60-day cutoff, idempotency, atomic failures, reservations, duplicates, SP gating, ledger preservation and tenant isolation');
  await c.end();
})().catch(async(error)=>{console.error(error);await c.end().catch(()=>{});process.exitCode=1});
